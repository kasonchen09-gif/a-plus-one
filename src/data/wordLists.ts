// 构建查词词典（单词 → 释义快速映射）
export function buildDictionary(wordLists: PresetWordList[]): Map<string, string> {
  const dict = new Map<string, string>()
  for (const list of wordLists) {
    for (const entry of list.entries) {
      if (!dict.has(entry.word.toLowerCase())) {
        dict.set(entry.word.toLowerCase(), entry.meaning)
      }
    }
  }
  return dict
}

// 获取所有单词
export function getAllWords(wordLists: PresetWordList[]): string[] {
  const set = new Set<string>()
  for (const list of wordLists) {
    for (const word of list.words) {
      set.add(word.toLowerCase())
    }
  }
  return Array.from(set)
}
